#!/usr/bin/env node
/**
 * Build a self-contained competitive comparison HTML for WeChat sharing.
 * Embeds docs/images/competitive/* as base64 data URLs.
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DOCS_DIR = path.join(ROOT, 'docs')
const SOURCE = path.join(DOCS_DIR, 'competitive-comparison.html')
const OUTPUT = path.join(DOCS_DIR, 'competitive-comparison.share.html')
const IMAGE_DIR = path.join(DOCS_DIR, 'images/competitive')

const MIME = {
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp'
}

function embedImages(html) {
  if (!fs.existsSync(IMAGE_DIR)) {
    throw new Error(`Missing image directory: ${IMAGE_DIR}`)
  }

  const files = fs
    .readdirSync(IMAGE_DIR)
    .filter(name => /\.(png|jpe?g|webp)$/i.test(name))
    .sort()

  if (!files.length) {
    throw new Error(`No images found in ${IMAGE_DIR}`)
  }

  let embedded = 0
  for (const file of files) {
    const ext = path.extname(file).toLowerCase()
    const mime = MIME[ext]
    if (!mime) continue

    const rel = `images/competitive/${file}`
    const abs = path.join(IMAGE_DIR, file)
    const dataUrl = `data:${mime};base64,${fs.readFileSync(abs).toString('base64')}`
    const before = html
    html = html.replaceAll(rel, dataUrl)
    if (html !== before) {
      embedded += 1
    }
  }

  return { html, embedded, total: files.length }
}

function main() {
  if (!fs.existsSync(SOURCE)) {
    throw new Error(`Missing source doc: ${SOURCE}`)
  }

  let html = fs.readFileSync(SOURCE, 'utf8')
  const { html: nextHtml, embedded, total } = embedImages(html)
  html = nextHtml

  const banner = [
    '<!--',
    '  Self-contained share build.',
    '  Generated by: npm run doc:competitive-share',
    `  Generated at: ${new Date().toISOString()}`,
    '  Send this single .html file via WeChat; images are embedded as base64.',
    '-->'
  ].join('\n')

  html = html.replace('<!doctype html>', `<!doctype html>\n${banner}`)

  fs.writeFileSync(OUTPUT, html)
  const sizeMb = (fs.statSync(OUTPUT).size / (1024 * 1024)).toFixed(2)
  console.log(`Built ${OUTPUT}`)
  console.log(`- Embedded ${embedded}/${total} images`)
  console.log(`- Size: ${sizeMb} MB`)
  console.log('Share competitive-comparison.share.html via WeChat.')
}

main()
