#!/usr/bin/env node
/**
 * Build a self-contained product intro HTML for sales sharing.
 * Embeds docs/images/mini-app/*.png as base64 data URLs.
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DOCS_DIR = path.join(ROOT, 'docs')
const SOURCE = path.join(DOCS_DIR, 'product-intro-sales.html')
const OUTPUT = path.join(DOCS_DIR, 'product-intro-sales.share.html')
const IMAGE_DIR = path.join(DOCS_DIR, 'images/mini-app')
const EXTRA_IMAGES = [
  {
    rel: '../images/home/hero-campus-jelly-v5.png',
    abs: path.join(ROOT, 'images/home/hero-campus-jelly-v5.png'),
    mime: 'image/png'
  }
]

function embedImages(html) {
  if (!fs.existsSync(IMAGE_DIR)) {
    throw new Error(`Missing screenshot directory: ${IMAGE_DIR}`)
  }

  const files = fs.readdirSync(IMAGE_DIR).filter(name => /\.png$/i.test(name)).sort()
  if (!files.length) {
    throw new Error(`No PNG screenshots found in ${IMAGE_DIR}`)
  }

  let embedded = 0
  for (const file of files) {
    const rel = `images/mini-app/${file}`
    const abs = path.join(IMAGE_DIR, file)
    const dataUrl = `data:image/png;base64,${fs.readFileSync(abs).toString('base64')}`
    const before = html
    html = html.replaceAll(rel, dataUrl)
    if (html !== before) embedded += 1
  }

  for (const image of EXTRA_IMAGES) {
    if (!fs.existsSync(image.abs)) {
      throw new Error(`Missing extra image: ${image.abs}`)
    }

    const dataUrl = `data:${image.mime};base64,${fs.readFileSync(image.abs).toString('base64')}`
    const before = html
    html = html.replaceAll(image.rel, dataUrl)
    if (html !== before) embedded += 1
  }

  return { html, embedded, total: files.length + EXTRA_IMAGES.length }
}

function main() {
  if (!fs.existsSync(SOURCE)) {
    throw new Error(`Missing source doc: ${SOURCE}`)
  }

  let html = fs.readFileSync(SOURCE, 'utf8')
  const result = embedImages(html)
  html = result.html

  const banner = [
    '<!--',
    '  Self-contained product intro build.',
    '  Generated by: npm run doc:product-sales-share',
    `  Generated at: ${new Date().toISOString()}`,
    '  Send this single .html file; product screenshots are embedded as base64.',
    '-->'
  ].join('\n')

  html = html.replace('<!doctype html>', `<!doctype html>\n${banner}`)
  fs.writeFileSync(OUTPUT, html)

  const sizeMb = (fs.statSync(OUTPUT).size / (1024 * 1024)).toFixed(1)
  console.log(`Built ${OUTPUT}`)
  console.log(`- Embedded ${result.embedded}/${result.total} screenshots`)
  console.log(`- Size: ${sizeMb} MB`)
}

main()
